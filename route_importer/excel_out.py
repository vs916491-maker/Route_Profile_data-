"""Write a Route to the SEC route-input workbook.

The first six sheets keep the template layout (README, Stations, Gradients,
Curves, Tunnels, SpeedLimits) so the SEC simulator's Route import is unchanged.
Extra information goes in sheets after them.
"""
from __future__ import annotations

import datetime as dt
import os

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from .merge import Route
from .units import fmt_chainage

HDR = Font(bold=True, color="FFFFFF")
HDR_FILL = PatternFill("solid", fgColor="1F4E78")
EXTRA_FILL = PatternFill("solid", fgColor="7F6000")
CALC_FILL = PatternFill("solid", fgColor="FFF2CC")
STATUS_FILL = {"OK": "C6EFCE", "WARN": "FFEB9C", "FAIL": "FFC7CE", "INFO": "DDEBF7"}


def _sheet(wb, title, headers, rows, widths=None, extra=False, calc_col=None):
    ws = wb.create_sheet(title)
    ws.append(headers)
    for c in ws[1]:
        c.font = HDR
        c.fill = EXTRA_FILL if extra else HDR_FILL
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    for row in rows:
        ws.append(row)
    if calc_col is not None:
        for r in ws.iter_rows(min_row=2):
            v = r[calc_col].value
            if isinstance(v, str) and ("Calculated" in v or "ASSUMED" in v):
                for c in r:
                    c.fill = CALC_FILL
    for i, h in enumerate(headers, 1):
        w = (widths or {}).get(h, max(11, len(str(h)) + 2))
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"
    return ws


def r3(x):
    return None if x is None else round(float(x), 3)


def write(route: Route, path: str, cfg: dict, files: list[str]):
    wb = Workbook()
    wb.remove(wb.active)
    cmt = cfg.get("sec_comment_column", True)

    # ---------------------------------------------------------------- README
    ws = wb.create_sheet("README")
    lines = [
        f"{route.name} - ROUTE input for the SEC simulator, generated by Route Importer",
        "",
        f"Generated: {dt.datetime.now():%Y-%m-%d %H:%M}",
        "SOURCE drawings:",
        *[f"  {os.path.basename(f)}" for f in files],
        f"Route extent: {fmt_chainage(route.start)} to {fmt_chainage(route.end)}  "
        f"({route.end - route.start:.0f} m)",
        "",
        "Units (as the SEC simulator expects)",
        "  Chainage in m (negative before km 0). Drawing chainages in km+m, km or m are converted.",
        "  Gradient in permil (‰), + = rising with increasing chainage. % x 10 = ‰ ; 1 in N = 1000/N ‰ ;",
        "  rise over length = rise/length x 1000. Change points at each vertical curve: "
        f"{cfg.get('gradient_change_at', 'vpi').upper()} (setting gradient_change_at: VPI = middle, PVT = end, PVC = start).",
        "  Radius in m, cant in mm, speed in km/h.",
        "",
        "Sheets",
        "  Stations, Gradients, Curves, Tunnels, SpeedLimits : SEC simulator input (same layout as the template).",
        "  VerticalCurves, Curve_Details, Cant, Rail_Levels : extra information from the drawings.",
        "  QA : checks - read every WARN / FAIL before using the file.   Sources : every value with sheet and OCR confidence.",
        "  Yellow rows = calculated or assumed values (not written in the drawing).",
        "",
        "How values were made",
        f"  Curves sheet extent: {cfg['curve_extent_for_sec']} "
        "(arc_plus_half_transitions = circular arc + half of each transition, same curve-resistance work).",
        f"  Cant where the drawing has none: transition length / ramp (default 1 in {cfg['cant_ramp_1_in']}), "
        f"max {cfg['max_cant_mm']} mm.",
        f"  Speed where the drawing has none: line speed {cfg['line_speed_kmh']} km/h; on curves "
        f"V = sqrt(127 x R x (Ca + Cd) / G), Cd = {cfg['cant_deficiency_mm']} mm, G = {cfg['cant_gauge_mm']} mm,",
        f"  rounded down to {cfg['speed_round_down_kmh']} km/h, applied from TS to ST. Marked 'Calculated'.",
        f"  Dwell {cfg['dwell_s']} s; terminals {cfg['terminal_dwell_s']} s.",
        "  Tunnels: CAD drawings - from START/END OF U/G RAMP, C&C, TBM, ELEVATED RAMP marks (see QA); "
        "PDF band drawings - not read, enter underground sections manually.",
        "",
        "Import: Route tab -> Import Excel / CSV -> this file.",
    ]
    for ln in lines:
        ws.append([ln])
    ws.column_dimensions["A"].width = 120

    # ------------------------------------------------------------- SEC sheets
    _sheet(wb, "Stations", ["name", "chainage_m", "dwell_s"],
           [[s["name"], r3(s["ch"]), s["dwell"]] for s in route.stations], {"name": 28})

    h = ["from_m", "permil"] + (["comment"] if cmt else [])
    _sheet(wb, "Gradients", h,
           [[r3(g["from"]), g["permil"]] + ([g["comment"]] if cmt else []) for g in route.gradients],
           {"comment": 48}, calc_col=2 if cmt else None)

    h = ["from_m", "to_m", "radius_m"] + (["comment"] if cmt else [])
    _sheet(wb, "Curves", h,
           [[c["sec_from"], c["sec_to"], c["R"]] +
            ([("Estimated end (off-sheet)" if c["partial"] else "From drawing")] if cmt else [])
            for c in route.curves], {"comment": 30})

    _sheet(wb, "Tunnels", ["from_m", "to_m"], [[r3(a), r3(b)] for a, b in route.tunnels])

    h = ["from_m", "kmh"] + (["comment"] if cmt else [])
    _sheet(wb, "SpeedLimits", h,
           [[r3(s["from"]), s["kmh"]] + ([s["comment"]] if cmt else []) for s in route.speeds],
           {"comment": 60}, calc_col=2 if cmt else None)

    # ------------------------------------------------------------ extra sheets
    _sheet(wb, "VerticalCurves",
           ["vpi_m", "start_m", "end_m", "radius_m", "length_m", "grade_in_permil", "grade_out_permil",
            "type", "comment", "source"],
           [[r3(v["vpi"]), r3(v["start"]), r3(v["end"]), v["R"], r3(v["L"]), v["g_in"], v["g_out"],
             v["type"], v["comment"], v["src"]] for v in route.vcurves],
           {"source": 40, "comment": 26}, extra=True)

    _sheet(wb, "Curve_Details",
           ["TS_m", "SC_m", "CS_m", "ST_m", "radius_m", "arc_length_m", "transition_in_m", "transition_out_m",
            "cant_mm", "speed_calc_kmh", "speed_limit_kmh", "speed_source", "sec_from_m", "sec_to_m",
            "curve_no", "direction", "source"],
           [[r3(c["ts"]), r3(c["sc"]), r3(c["cs"]), r3(c["st"]), c["R"], c["arc_L"], c["TL_in"], c["TL_out"],
             c["cant_mm"], c["v_calc"], c["v_limit"], c.get("v_src", ""), c["sec_from"], c["sec_to"],
             c.get("curve_no", ""), c.get("dir") or "not in drawing", c["src"]] for c in route.curves],
           {"source": 40, "direction": 20}, extra=True)

    _sheet(wb, "Cant",
           ["runout_in_start_m", "full_cant_from_m", "full_cant_to_m", "runout_out_end_m", "radius_m",
            "cant_mm", "ramp_1_in_N", "ramp_permil", "runout_in_m", "runout_out_m", "comment"],
           [[r3(c["ts"]), r3(c["sc"]), r3(c["cs"]), r3(c["st"]), c["R"], c["cant_mm"], c["ramp_n"],
             c["ramp_permil"], c["runout_in"], c["runout_out"], c["comment"]] for c in route.cant],
           {"comment": 60}, extra=True, calc_col=10)

    chs = sorted(set(route.rail) | set(route.ground))
    _sheet(wb, "Rail_Levels", ["chainage_m", "rail_level_m", "ground_level_m"],
           [[c, route.rail.get(c), route.ground.get(c)] for c in chs], extra=True)

    # --------------------------------------------------------------------- QA
    order = {"FAIL": 0, "WARN": 1, "INFO": 2, "OK": 3}
    qa = sorted(route.qa, key=lambda q: (order.get(q["status"], 9), q["ch"] if q["ch"] is not None else -1e9))
    n = {k: sum(q["status"] == k for q in qa) for k in order}
    ws = _sheet(wb, "QA", ["status", "check", "chainage_m", "chainage", "expected", "found", "note"],
                [[q["status"], q["check"], r3(q["ch"]), fmt_chainage(q["ch"]) if q["ch"] is not None else "",
                  q["expected"], q["found"], q["note"]] for q in qa],
                {"note": 90, "check": 24}, extra=True)
    for row in ws.iter_rows(min_row=2):
        f = STATUS_FILL.get(row[0].value)
        if f:
            row[0].fill = PatternFill("solid", fgColor=f)
    ws.insert_rows(1)
    ws["A1"] = (f"Summary: {n['FAIL']} FAIL, {n['WARN']} WARN, {n['INFO']} INFO, {n['OK']} OK  "
                "- fix or accept every FAIL / WARN before using the route.")
    ws["A1"].font = Font(bold=True)
    ws.freeze_panes = "A3"

    _sheet(wb, "Sources", ["sheet", "band", "text_read", "value", "chainage_m", "confidence", "method"],
           [[s["sheet"], s["band"], s["text"], s["value"], r3(s["ch"]), s["conf"], s["method"]]
            for s in sorted(route.sources, key=lambda s: (s["ch"] if s["ch"] is not None else 0))],
           {"sheet": 30, "text_read": 24}, extra=True)
    wb.save(path)
    return path
